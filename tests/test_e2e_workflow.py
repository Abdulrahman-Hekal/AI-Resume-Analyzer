import io
import docx
import pytest
from app.db.seed import seed_all

def make_docx_bytes(text: str) -> bytes:
    doc = docx.Document()
    for line in text.splitlines():
        if line.strip():
            doc.add_paragraph(line.strip())
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


@pytest.mark.asyncio
async def test_complete_21_step_end_to_end_workflow(client, db_session):
    """
    Executes the exact 21-step workflow mandated by the SRS audit:
    1. Clean database state
    2. Seed demo data (users, jobs, knowledge base)
    3. FastAPI app is live
    4. Landing / health check verified
    5. Register a new user
    6. Login with new user credentials
    7. Upload a sample DOCX resume
    8. Trigger resume analysis
    9. Verify extracted structured information (skills, education, exp)
    10. Verify identified strengths and weaknesses
    11. Request job recommendations
    12. Verify matching scores (0.0 - 100.0)
    13. Inspect a recommended job
    14. Verify matched skills
    15. Verify missing skills
    16. Verify recommendation explanation generated by Agent 2
    17. Open Career Advisor
    18. Ask a career development question
    19. Verify RAG vector retrieval
    20. Verify retrieved sources / citations
    21. Verify generated answer incorporates retrieved context
    """
    # Step 1 & 2: Clean database state & Seed demo data
    await seed_all(db=db_session)

    # Step 3 & 4: FastAPI server & Landing / health check
    health_res = client.get("/api/health")
    assert health_res.status_code == 200
    assert health_res.json()["status"] == "healthy"

    # Step 5: Register a new user
    reg_data = {
        "email": "graduation_candidate@test.edu",
        "password": "SecurePassword2026!",
        "full_name": "Graduation Candidate",
        "role": "user"
    }
    reg_res = client.post("/api/auth/register", json=reg_data)
    assert reg_res.status_code == 201

    # Step 6: Login
    login_res = client.post("/api/auth/login", json={
        "email": "graduation_candidate@test.edu",
        "password": "SecurePassword2026!"
    })
    assert login_res.status_code == 200
    token = login_res.json()["access_token"]
    auth_headers = {"Authorization": f"Bearer {token}"}

    # Step 7: Upload a sample DOCX resume
    sample_resume_text = (
        "Alex Morgan\n"
        "Email: alex.morgan@example.com | Phone: (555) 789-0123\n"
        "Location: San Francisco, CA\n\n"
        "Professional Summary:\n"
        "Versatile Full Stack Engineer with 3+ years experience building cloud web applications.\n"
        "Specialized in Python, FastAPI, React, PostgreSQL, and Docker containerization.\n\n"
        "Technical Skills:\n"
        "Python, FastAPI, React, JavaScript, TypeScript, PostgreSQL, Docker, Git, REST API, Redis.\n\n"
        "Experience:\n"
        "Software Engineer at CloudNative Systems (2 years)\n"
        "- Engineered high-throughput REST APIs using FastAPI and PostgreSQL.\n"
        "- Containerized microservices using Docker and orchestrated deployments.\n\n"
        "Education:\n"
        "Bachelor of Science in Computer Science, University of California, 2022.\n\n"
        "Projects:\n"
        "- Scalable Distributed Task Queue built with Python and Redis.\n"
        "- Realtime Monitoring Dashboard using React and WebSockets."
    )
    docx_bytes = make_docx_bytes(sample_resume_text)
    files = {"file": ("alex_morgan_resume.docx", docx_bytes, "application/vnd.openxmlformats-officedocument.wordprocessingml.document")}
    upload_res = client.post("/api/resumes", files=files, headers=auth_headers)
    assert upload_res.status_code == 201
    resume_id = upload_res.json()["id"]

    # Step 8: Analyze the resume (Agent 1)
    analyze_res = client.post(f"/api/resumes/{resume_id}/analyze", headers=auth_headers)
    assert analyze_res.status_code == 200
    analysis = analyze_res.json()

    # Step 9: Verify structured resume information
    assert analysis["candidate_name"] is not None
    assert "alex.morgan@example.com" in analysis["email"]
    assert len(analysis["technical_skills"]) >= 3
    assert len(analysis["education"]) >= 1
    assert len(analysis["experience"]) >= 1

    # Step 10: Verify strengths and weaknesses
    assert len(analysis["strengths"]) > 0
    assert len(analysis["weaknesses"]) > 0
    assert len(analysis["recommended_improvements"]) > 0

    # Step 11: Request job recommendations (Agent 2)
    rec_res = client.post(f"/api/resumes/{resume_id}/recommendations", headers=auth_headers)
    assert rec_res.status_code == 200
    recs_data = rec_res.json()
    assert recs_data["total"] >= 1

    # Step 12: Verify matching scores
    top_rec = recs_data["recommendations"][0]
    assert 0.0 <= top_rec["match_score"] <= 100.0
    assert 0.0 <= top_rec["skill_score"] <= 100.0
    assert 0.0 <= top_rec["experience_score"] <= 100.0
    assert 0.0 <= top_rec["education_score"] <= 100.0
    assert 0.0 <= top_rec["semantic_score"] <= 100.0

    # Step 13: Open a recommended job
    job_id = top_rec["job_id"]
    job_res = client.get(f"/api/jobs/{job_id}")
    assert job_res.status_code == 200
    job = job_res.json()
    assert job["title"] is not None

    # Step 14: Verify matched skills
    assert isinstance(top_rec["matching_skills"], list)

    # Step 15: Verify missing skills
    assert isinstance(top_rec["missing_skills"], list)

    # Step 16: Verify recommendation explanation
    assert len(top_rec["match_explanation"]) > 25

    # Step 17: Open Career Advisor (Agent 3)
    # Step 18: Ask a career question
    question_payload = {
        "question": "What roadmap should I follow to transition from fullstack to cloud infrastructure?",
        "resume_id": resume_id,
        "target_role": "Cloud DevOps Engineer"
    }
    career_res = client.post("/api/career/questions", json=question_payload, headers=auth_headers)
    assert career_res.status_code == 200
    career_data = career_res.json()

    # Step 19: Verify RAG retrieval
    assert career_data["grounded_by_rag"] is True

    # Step 20: Verify retrieved sources/citations
    assert len(career_data["retrieved_sources"]) > 0
    top_source = career_data["retrieved_sources"][0]
    assert top_source["document_title"] is not None
    assert top_source["similarity_score"] > 0.0
    assert len(top_source["snippet"]) > 10

    # Step 21: Verify generated answer uses retrieved context & structured roadmap
    assert len(career_data["answer"]) > 30
    assert len(career_data["career_roadmap"]) == 3
    assert len(career_data["suggested_certifications"]) > 0
